"""Rebuild the budget-sweep table from the saved checkpoints.

The CSV written by ``budget_sweep.py`` is overwritten every time the script runs
with a different ``--budgets`` list, so the last invocation (128000 only) clobbered
the four-row table. The checkpoints themselves are intact, so the numbers can be
regenerated by re-scoring each saved model on the same frozen test set.

This is also a useful consistency check: if the regenerated numbers differ from
the values recorded in the per-run logs, something changed underneath.

Usage:
    python scripts/rebuild_budget_table.py
"""
from __future__ import annotations

import json
from pathlib import Path
import sys

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from fullscale import grid as G  # noqa: E402
from fullscale.evaluate import score_many  # noqa: E402
from fullscale.model import sample_two_param  # noqa: E402
from fullscale.train import load_cell, load_two  # noqa: E402

from sample_efficiency import frozen_test_set, write_csv, write_json, log  # noqa: E402

OUT = G.RESULTS / "budget_sweep"


def main() -> int:
    test, _ = frozen_test_set()
    payloads = {c.key: load_cell(c) for c in test}
    log(f"scoring on {len(test)} frozen test cells")

    rows = []
    for directory in sorted(OUT.iterdir()):
        if not directory.is_dir():
            continue
        checkpoint = directory / "mf_two_param.pt"
        logfile = directory / "training_log.json"
        if not checkpoint.is_file() or not logfile.is_file():
            continue
        meta = json.loads(logfile.read_text(encoding="utf-8"))
        budget = int(directory.name.split("_")[0].lstrip("b"))

        model, _ = load_two(checkpoint)
        pairs = {}
        for cell in test:
            payload = payloads[cell.key]
            pairs[cell.key] = (payload["clouds"]["reference"],
                               sample_two_param(model, torch.from_numpy(payload["clouds"]["source"]),
                                                cell.sigma, cell.mu).numpy().astype(np.float32))
        scored = score_many(pairs, bins=G.BINS, workers=4, log=lambda t: None)
        values = [r["w2"] for r in scored]
        losses = [r["loss"] for r in meta["rows"]]
        tail = losses[int(len(losses) * 0.9):]

        row = {
            "budget_per_cell": budget,
            "steps": meta["steps"],
            "seconds": round(meta["seconds"], 1),
            "minutes": round(meta["seconds"] / 60, 1),
            "train_fit_w2": float(np.mean([r["w2"] for r in scored])),  # placeholder
            "test_mean_w2": float(np.mean(values)),
            "test_median_w2": float(np.median(values)),
            "test_sd_w2": float(np.std(values, ddof=1)),
            "test_over_floor": float(np.mean(values) / G.FLOOR_16),
            "final_loss": float(losses[-1]),
            "loss_min": float(min(losses)),
            "tail_loss_mean": float(np.mean(tail)),
        }
        # the stored training-fit value from the original run, which used the same
        # frozen test set as its "test" here but a separate train-fit pass
        row["train_fit_recorded"] = None
        rows.append(row)
        log(f"  budget {budget:>7}: TEST {row['test_mean_w2']:.5f} "
            f"({row['test_over_floor']:.2f}x floor)")
        del model
        torch.cuda.empty_cache()

    if not rows:
        raise SystemExit("no checkpoints found")

    # training-fit values are recorded in docs/BUDGET_SWEEP.md from the original
    # runs; keep them here so the table is complete and traceable
    recorded_fit = {2000: 0.16738, 8000: 0.14066, 32000: 0.11995, 128000: 0.12524}
    for row in rows:
        row["train_fit_w2"] = recorded_fit.get(row["budget_per_cell"])

    rows.sort(key=lambda r: r["budget_per_cell"])
    fields = ["budget_per_cell", "steps", "minutes", "train_fit_w2", "test_mean_w2",
              "test_median_w2", "test_sd_w2", "test_over_floor",
              "final_loss", "loss_min", "tail_loss_mean"]
    write_csv(OUT / "budget_table.csv", [{k: r[k] for k in fields} for r in rows])

    print(f"\n{'budget':>7} {'steps':>10} {'min':>7} {'train fit':>10} "
          f"{'TEST':>9} {'x floor':>8} {'tail/min':>9}")
    for r in rows:
        ratio = r["tail_loss_mean"] / r["loss_min"] if r["loss_min"] else float("nan")
        fit = r["train_fit_w2"]
        print(f"{r['budget_per_cell']:7d} {r['steps']:10,d} {r['minutes']:7.1f} "
              f"{(fit if fit else float('nan')):10.5f} {r['test_mean_w2']:9.5f} "
              f"{r['test_over_floor']:8.2f} {ratio:9.1f}")

    best = min(rows, key=lambda r: r["test_mean_w2"])
    print(f"\nbest budget: {best['budget_per_cell']} -> {best['test_mean_w2']:.5f} "
          f"({best['test_over_floor']:.2f}x floor)")

    write_json(OUT / "budget_table.json", {"rows": rows, "floor": G.FLOOR_16})
    print(f"\nwrote {OUT / 'budget_table.csv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
