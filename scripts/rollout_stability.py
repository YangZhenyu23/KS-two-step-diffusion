"""Rollout stability: does the generator stay on the physical manifold when iterated?

Why this experiment
-------------------
A reviewer's objection to a one-step generator is that a small one-step distributional
error says nothing about what happens when the map is applied repeatedly. Two failure
modes are possible and neither is visible in a single-step W2:

  1. the map is not idempotent - the cloud keeps drifting, so k applications diverge;
  2. the map is stable but converges to the wrong invariant object - the cloud
     collapses or spreads without bound.

The KS equation here is an advected-diffusion: the shear pushes mass in +x and the
diffusion spreads it. Applying the learned one-step map k times therefore has a
physical meaning: it is "run the model for k*T time with a coarse step". The reference
for that comparison is the *physical simulator* run for k*T, which we can also compute.

What is measured
----------------
For a grid of (sigma, mu) cells and k = 1, 2, 4, 8:

  * ``w2_to_phys_k``   W2 between the k-times-applied generator output and the true
                       physical solution at time k*T (same initial cloud);
  * ``w2_to_prev``     W2 between application k and k-1, i.e. does the map converge
                       or keep moving? A map approaching a fixed point has this -> 0.
  * physical invariants (mass, centroid, second moments, anisotropy) so the failure
                       can be described physically rather than only metrically;
  * ``diverged``       whether any particle left a generous box, or the cloud radius
                       blew up.

The physical reference at k*T is generated by the upstream simulator with ``t = k*T``
and the *same* initial cloud, so the comparison has no Monte-Carlo confound beyond the
Brownian path (which is redrawn, and is why the floor is reported alongside).

Cost
----
Simulation is the expensive part: 100k particles at T=0.02 takes ~83 s, and k*T scales
roughly linearly. To keep the run bounded the physical references are computed at 30k
particles (the simulator is O(N^2), so 100k would be ~11x slower per call). The
generator is evaluated on 100k particles, then subsampled to the same 30k for scoring.

Usage:
    python scripts/rollout_stability.py --cells 6 --ks 1 2 4 8 --n 30000
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import sys
import time

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "upstream" / "MF-DeepParticle" / "deepparticle"))

from fullscale import grid as G  # noqa: E402
from fullscale.train import load_cell, load_two  # noqa: E402
from fullscale.model import sample_two_param  # noqa: E402
from twoparam.data import unit_ball  # noqa: E402

OUT = G.RESULTS / "rollout"

# Cells spanning the box, all held out from the LHS-40 design.
CELLS = [(0, 1), (3, 4), (9, 6), (13, 7), (19, 9), (11, 9)]


def exact_w2(a: np.ndarray, b: np.ndarray) -> float:
    """Exact W2 between equal-size clouds (POT network simplex, float64)."""
    import ot
    from scipy.spatial.distance import cdist

    a = np.ascontiguousarray(a, dtype=np.float64)
    b = np.ascontiguousarray(b, dtype=np.float64)
    cost = cdist(a, b, metric="sqeuclidean")
    n = len(a)
    w = np.full(n, 1.0 / n)
    value, info = ot.emd2(w, w, cost, log=True, numItermax=5_000_000)
    if int(info.get("result_code", -1)) != 1:
        raise RuntimeError(f"OT failed: {info.get('warning')}")
    return math.sqrt(max(value, 0.0))


def simulate(initial: np.ndarray, sigma: float, mu: float, final_time: float,
             noise_seed: int, device: str) -> np.ndarray:
    """Physical KS solution at ``final_time``, same initial cloud, fresh Brownian path."""
    from training.protocol import simulate_original

    np.random.seed(noise_seed)
    torch.manual_seed(noise_seed)
    return simulate_original(
        torch.from_numpy(initial), float(sigma), mu=float(mu),
        chi=16 * math.pi, delta=0.1, t=float(final_time), dt=0.005,
        chunk=256, device=device,
    ).numpy()


def invariants(cloud: np.ndarray) -> dict:
    """Physical readouts that describe *how* the cloud failed, not just that it did."""
    centred = cloud - cloud.mean(0)
    covariance = np.cov(centred.T)
    eigenvalues = np.sort(np.linalg.eigvalsh(covariance))[::-1]
    return {
        "centroid": cloud.mean(0).tolist(),
        "eig_first": float(eigenvalues[0]),
        "eig_second": float(eigenvalues[1]),
        "eig_third": float(eigenvalues[2]),
        "anisotropy": float(eigenvalues[0] / max(eigenvalues[1], 1e-12)),
        "radius_rms": float(np.sqrt((centred ** 2).sum(1).mean())),
        "x_min": float(cloud[:, 0].min()),
        "x_max": float(cloud[:, 0].max()),
        "mass": float(len(cloud)),
        "finite": bool(np.isfinite(cloud).all()),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cells", type=int, default=6)
    ap.add_argument("--ks", type=int, nargs="+", default=[1, 2, 4, 8])
    ap.add_argument("--n", type=int, default=30000, help="particles for simulation and scoring")
    ap.add_argument("--score-n", type=int, default=3000, help="subsample used for exact OT")
    ap.add_argument("--seed", type=int, default=88)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--bins", type=int, default=16)
    a = ap.parse_args()

    torch.set_num_threads(1)
    OUT.mkdir(parents=True, exist_ok=True)
    log = lambda text: print(f"[{time.strftime('%H:%M:%S')}] {text}", flush=True)

    model, _ = load_two(G.RESULTS / "optimal_budget_ablation" / "two_32000" / "mf_two_param.pt",
                        a.device)
    initial = unit_ball(a.n, 88)

    rng = np.random.default_rng(20261116)
    index = rng.choice(a.n, size=min(a.score_n, a.n), replace=False)

    rows = []
    for cell_index, (i, j) in enumerate(CELLS[: a.cells], start=1):
        cell = G.Cell(i, j)
        sigma, mu = cell.sigma, cell.mu
        log(f"=== {cell_index}/{min(a.cells, len(CELLS))} {cell.key} "
            f"sigma={sigma:g} mu={mu:g} ===")

        # k applications of the learned one-step map, starting from the same cloud.
        cloud = torch.from_numpy(initial.astype(np.float32))
        generated = {}
        for k in a.ks:
            # apply from scratch each time so an error at step 3 is not hidden by re-use
            current = cloud
            for _ in range(k):
                current = sample_two_param(model, current, sigma, mu, steps=1)
            generated[k] = current.numpy().astype(np.float64)

        # physical reference at k*T, same initial cloud
        physical = {}
        for k in a.ks:
            started = time.perf_counter()
            seed = 7_770_000 + 13 * (i * 10 + j) + 101 * k
            physical[k] = simulate(initial, sigma, mu, G.FINAL_TIME * k, seed, a.device)
            log(f"  physical t={G.FINAL_TIME * k:.3f} ({k}xT): "
                f"{time.perf_counter() - started:.0f}s")

        previous_generated = None
        previous_physical_ref = None
        for k in a.ks:
            gen = generated[k]
            phys = physical[k]
            w2 = exact_w2(gen[index], phys[index])
            # how far did one more application move the cloud?
            step = None if previous_generated is None else exact_w2(gen[index], previous_generated[index])
            # the physics also moves between k-1 and k; compare like with like
            phys_step = (None if previous_physical_ref is None
                         else exact_w2(phys[index], previous_physical_ref[index]))
            inv = invariants(gen)
            rows.append({
                "key": cell.key, "sigma": sigma, "mu": mu, "k": k,
                "w2_to_physical": w2,
                "w2_step_from_prev": step,
                "physical_step_w2": phys_step,
                "step_ratio": (None if (step is None or not phys_step) else step / phys_step),
                "generated": inv,
                "physical": invariants(phys),
                "diverged": (not inv["finite"]) or inv["radius_rms"] > 50.0,
            })
            previous_generated, previous_physical_ref = gen, phys
            log(f"  k={k}: W2 vs physics {w2:.5f}"
                + (f"  step {step:.5f} (physics moved {phys_step:.5f})" if step is not None else ""))

    # floor at the same scoring size, from two independent physical paths
    floors = []
    for cell_index, (i, j) in enumerate(CELLS[: a.cells], start=1):
        cell = G.Cell(i, j)
        first = simulate(initial, cell.sigma, cell.mu, G.FINAL_TIME,
                         8_880_000 + i * 10 + j, a.device)
        second = simulate(initial, cell.sigma, cell.mu, G.FINAL_TIME,
                          9_990_000 + i * 10 + j, a.device)
        floors.append({"key": cell.key, "floor": exact_w2(first[index], second[index])})
        log(f"  floor {cell.key}: {floors[-1]['floor']:.5f}")
    floor_mean = float(np.mean([f["floor"] for f in floors]))

    payload = {
        "cells": a.cells, "ks": a.ks, "n_simulate": a.n, "score_n": int(len(index)),
        "seed": a.seed, "floor_mean": floor_mean, "floors": floors, "rows": rows,
    }
    (OUT / "rollout.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")

    print(f"\nfloor at n={len(index)}: {floor_mean:.5f}")
    print(f"{'cell':>8} {'k':>3} {'W2/phys':>9} {'W2/floor':>9} {'step':>8} "
          f"{'phys step':>10} {'ratio':>7} {'r_rms':>8} {'aniso':>7}")
    for row in rows:
        gen = row["generated"]
        print(f"{row['key']:>8} {row['k']:3d} {row['w2_to_physical']:9.5f} "
              f"{row['w2_to_physical'] / floor_mean:9.2f} "
              f"{(row['w2_step_from_prev'] if row['w2_step_from_prev'] is not None else float('nan')):8.5f} "
              f"{(row['physical_step_w2'] if row['physical_step_w2'] is not None else float('nan')):10.5f} "
              f"{(row['step_ratio'] if row['step_ratio'] is not None else float('nan')):7.2f} "
              f"{gen['radius_rms']:8.3f} {gen['anisotropy']:7.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
